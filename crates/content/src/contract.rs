use crate::types::*;
use schemars::{JsonSchema, generate::SchemaSettings};
use serde_json::{Value, json};
use ts_rs::{Config, TS};
pub fn schema<T: JsonSchema>() -> Value {
    let mut root = serde_json::to_value(
        SchemaSettings::draft2020_12()
            .into_generator()
            .into_root_schema_for::<T>(),
    )
    .expect("content schema");
    fn required(v: &mut Value) {
        match v {
            Value::Object(o) => {
                if let Some(Value::Object(p)) = o.get("properties") {
                    o.insert(
                        "required".into(),
                        json!(
                            p.keys()
                                .filter(|k| k.as_str() != "building" && k.as_str() != "archetypes")
                                .collect::<Vec<_>>()
                        ),
                    );
                }
                for v in o.values_mut() {
                    required(v);
                }
            }
            Value::Array(a) => a.iter_mut().for_each(required),
            _ => {}
        }
    }
    required(&mut root);
    root
}
