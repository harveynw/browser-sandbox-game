//! Production tick wiring: ordering and conditions only; gameplay lives in systems.
use super::admission::admission;
use super::runtime::{begin_missions, combat, missions, police, repairs};
use super::{TickOutcome, TickPhase, runtime::Scratch, tick_schedule};
use crate::systems::movement::motors;
use bevy_ecs::prelude::*;
pub(crate) fn initialize(host: &mut World, network: crate::transport::Network) {
    host.insert_non_send(network);
    host.init_resource::<Scratch>();
    host.init_resource::<crate::systems::planning::Planning>();
    host.init_resource::<TickOutcome>();
    host.init_resource::<crate::replication::publication::Publication>();
}
pub(crate) fn build() -> Schedule {
    let mut schedule = tick_schedule();
    schedule.add_systems(
        (
            admission,
            (
                crate::systems::weapons::present_shots.run_if(crate::ecs::healthy),
                crate::systems::weapons::retire_shots,
            )
                .chain(),
            crate::ecs::checkpoints::death_checkpoint(),
            crate::ecs::checkpoints::reactions(),
        )
            .chain()
            .in_set(TickPhase::Admission),
    );
    schedule.add_systems(
        (
            crate::systems::planning::begin,
            crate::systems::police::native::roster.run_if(crate::ecs::healthy),
            crate::systems::population::native::direct.run_if(crate::ecs::healthy),
            crate::systems::planning::prepare_geometry.run_if(crate::ecs::healthy),
            crate::systems::population::traffic::plan_routes.run_if(crate::ecs::healthy),
            crate::systems::population::traffic::drive.run_if(crate::ecs::healthy),
            crate::systems::population::pedestrians::decide.run_if(crate::ecs::healthy),
            crate::systems::police::driving::drive.run_if(crate::ecs::healthy),
            crate::systems::planning::finish.run_if(crate::ecs::healthy),
        )
            .chain()
            .in_set(TickPhase::Planning),
    );
    schedule.add_systems(
        (
            motors::begin_movement,
            motors::move_pedestrians.run_if(crate::ecs::healthy),
            motors::move_vehicles.run_if(crate::ecs::healthy),
            motors::move_players.run_if(crate::ecs::healthy),
            crate::systems::impact::calculate_vehicle_damage.run_if(crate::ecs::healthy),
            crate::systems::impact::apply_vehicle_damage.run_if(crate::ecs::healthy),
            crate::systems::impact::calculate_pedestrian_damage.run_if(crate::ecs::healthy),
            crate::systems::impact::apply_pedestrian_damage.run_if(crate::ecs::healthy),
            crate::systems::impact_consequences::present_impacts.run_if(crate::ecs::healthy),
            crate::systems::impact_consequences::find_disabled_occupants
                .run_if(crate::ecs::healthy),
            crate::systems::impact_consequences::recover_occupants.run_if(crate::ecs::healthy),
            crate::systems::impact_consequences::fail_crash_missions.run_if(crate::ecs::healthy),
            crate::replication::apply_control_transitions.run_if(crate::ecs::healthy),
            crate::replication::retire_control_transitions,
            crate::systems::lifecycle::players::retire_death_messages,
            crate::ecs::checkpoints::reactions(),
            motors::recover_pedestrians.run_if(crate::ecs::healthy),
        )
            .chain()
            .in_set(TickPhase::Movement),
    );
    schedule.add_systems(
        (
            combat,
            (
                crate::systems::police::officers::native::deploy,
                crate::systems::police::officers::native::decide,
            )
                .chain()
                .run_if(crate::ecs::healthy),
            (
                crate::systems::weapons::update_officer_weapons,
                crate::systems::weapons::execute_officer_shots,
            )
                .chain()
                .run_if(crate::ecs::healthy),
            (
                crate::systems::weapons::present_shots.run_if(crate::ecs::healthy),
                crate::systems::weapons::retire_shots,
            )
                .chain(),
            crate::ecs::checkpoints::death_checkpoint(),
            crate::systems::lifecycle::despawn_expired_pedestrians.run_if(crate::ecs::healthy),
            crate::systems::weapons::request_automatic_shots.run_if(crate::ecs::healthy),
            crate::systems::weapons::execute_automatic.run_if(crate::ecs::healthy),
            (
                crate::systems::weapons::present_shots.run_if(crate::ecs::healthy),
                crate::systems::weapons::retire_shots,
            )
                .chain(),
            crate::ecs::checkpoints::death_checkpoint(),
            crate::systems::lifecycle::players::advance_weapon_timers.run_if(crate::ecs::healthy),
            crate::systems::lifecycle::players::respawn_players.run_if(crate::ecs::healthy),
            crate::systems::lifecycle::players::reset_respawned_missions
                .run_if(crate::ecs::healthy),
            crate::replication::apply_control_transitions.run_if(crate::ecs::healthy),
            crate::replication::retire_control_transitions,
            crate::systems::lifecycle::restore_vehicles.run_if(crate::ecs::healthy),
            crate::systems::population::release_restored_vehicles.run_if(crate::ecs::healthy),
            crate::systems::lifecycle::remove_orphaned_incapacitation.run_if(crate::ecs::healthy),
            crate::ecs::checkpoints::reactions(),
            crate::systems::police::reset_respawned_players.run_if(crate::ecs::healthy),
        )
            .chain()
            .in_set(TickPhase::Combat),
    );
    schedule.add_systems(
        (
            police,
            crate::systems::police::perception::perceive.run_if(crate::ecs::healthy),
            crate::systems::police::native::arrest.run_if(crate::ecs::healthy),
            crate::systems::police::native::fail_arrested_missions.run_if(crate::ecs::healthy),
            crate::replication::apply_control_transitions.run_if(crate::ecs::healthy),
            crate::replication::retire_control_transitions,
        )
            .chain()
            .in_set(TickPhase::Police),
    );
    schedule.add_systems(
        (
            crate::sessions::native::failed_motors,
            crate::ecs::checkpoints::disconnects().run_if(crate::ecs::healthy),
            crate::systems::missions::native::refresh_proxies.run_if(crate::ecs::healthy),
        )
            .chain()
            .in_set(TickPhase::FailedPeers),
    );
    schedule.add_systems(
        (
            repairs,
            crate::systems::repairs::native::update.run_if(crate::ecs::healthy),
        )
            .chain()
            .in_set(TickPhase::Repairs),
    );
    schedule.add_systems(
        (
            begin_missions,
            crate::systems::missions::native::progress.run_if(crate::ecs::healthy),
            crate::replication::apply_control_transitions.run_if(crate::ecs::healthy),
            crate::replication::retire_control_transitions,
            crate::systems::missions::native::remove_retired.run_if(crate::ecs::healthy),
            crate::systems::missions::native::refresh_proxies.run_if(crate::ecs::healthy),
            crate::systems::missions::native::persist_rewards.run_if(crate::ecs::healthy),
            crate::systems::missions::native::apply_rewards.run_if(crate::ecs::healthy),
            crate::systems::missions::native::publish_status.run_if(crate::ecs::healthy),
            missions,
        )
            .chain()
            .in_set(TickPhase::Missions),
    );
    schedule.add_systems(crate::ecs::checkpoints::publication().in_set(TickPhase::Publish));
    schedule.add_systems(crate::replication::egress::flush.in_set(TickPhase::Flush));
    // Chained native systems apply deferred lifecycle changes before dependent phases.
    schedule
}
